/**
 * Stacks: RAW+JPEG pairs, bursts, Live Photos and the rest.
 *
 * Every operation is metadata-only, and the fake is written so that stays true by
 * construction: nothing here removes an asset from [com.justin13888.capsule.core.mock.MockState.assets].
 * Leaving a stack clears the membership register and un-suppresses the asset; it never
 * deletes, rewrites or merges the bytes underneath, which is what makes a buggy stack edit
 * unable to lose an original.
 */
class FakeStackRepository(
    private val backend: MockBackend,
) : StackRepository {
    private val prng = Prng(Prng.mixSeed(backend.library.spec.seed, "stack-writes"))

    override fun stack(id: StackId): Flow<Stack?> = backend.observe { state, _ -> state.stacks[id] }

    override suspend fun stackMembers(stackId: StackId): List<StackMember> {
        backend.gate(MockOperation.AssetRead)
        return backend.read { it.stackMembers[stackId]?.sortedBy(StackMember::sequenceOrder) }.orEmpty()
    }

    override suspend fun createStack(
        stackType: StackType,
        primaryAssetId: AssetId,
        assetIds: List<AssetId>,
    ): StackId {
        backend.gate(MockOperation.StackWrite)
        // A stack whose primary is not a member would collapse to something the user cannot
        // see, so this is a precondition rather than a recoverable failure.
        require(primaryAssetId in assetIds) { "the primary must be one of the members" }
        val now = backend.now()
        val stackId = StackId(DeterministicIds.uuidV7(now.toEpochMilli(), prng))
        backend.mutate { state ->
            state.stacks[stackId] =
                Stack(
                    id = stackId,
                    stackType = stackType.asWire(),
                    primaryAssetId = primaryAssetId,
                    coverAssetId = primaryAssetId,
                    isCollapsed = true,
                    isAutoGenerated = false,
                    createdAt = now,
                    modifiedAt = now,
                    detectedBy = DetectionMethod.Manual.asWire(),
                )
            val rows = state.stackMembers.getOrPut(stackId) { mutableListOf() }
            assetIds.forEachIndexed { index, assetId ->
                val asset = state.assets[assetId] ?: return@forEachIndexed
                rows += memberRow(stackId, assetId, index, StackMemberRole.Alternate, now)
                state.put(
                    asset.copy(
                        stack =
                            StackMembership(
                                stackId = stackId,
                                stackType = stackType.asWire(),
                                role = roleFor(assetId == primaryAssetId),
                                memberIndex = index,
                                isSuppressed = assetId != primaryAssetId,
                            ),
                    ),
                )
            }
        }
        return stackId
    }

    override suspend fun addMember(
        stackId: StackId,
        assetId: AssetId,
        role: StackMemberRole,
    ) {
        backend.gate(MockOperation.StackWrite)
        val stack = requireStack(stackId)
        val asset = backend.requireAsset(assetId)
        val now = backend.now()
        backend.mutate { state ->
            val rows = state.stackMembers.getOrPut(stackId) { mutableListOf() }
            rows += memberRow(stackId, assetId, rows.size, role, now)
            state.put(
                asset.copy(
                    stack =
                        StackMembership(
                            stackId = stackId,
                            stackType = stack.stackType,
                            role = StackRole.Member.asWire(),
                            memberIndex = rows.size - 1,
                            isSuppressed = true,
                        ),
                ),
            )
            state.stacks[stackId] = stack.copy(modifiedAt = now, isAutoGenerated = false)
        }
    }

    override suspend fun removeMember(
        stackId: StackId,
        assetId: AssetId,
    ) {
        backend.gate(MockOperation.StackWrite)
        val asset = backend.requireAsset(assetId)
        backend.mutate { state ->
            state.stackMembers[stackId]?.removeAll { it.assetId == assetId }
            // A stamped absence on the membership register, not a delete: leaving a stack is
            // the same kind of write as joining one, so it converges the same way.
            state.put(asset.copy(stack = null))
        }
    }

    override suspend fun setStackPrimary(
        stackId: StackId,
        primaryAssetId: AssetId,
    ) {
        backend.gate(MockOperation.StackWrite)
        val stack = requireStack(stackId)
        backend.mutate { state ->
            state.stacks[stackId] = stack.copy(primaryAssetId = primaryAssetId, modifiedAt = backend.now())
            // Choosing the best photo moves a pointer and re-suppresses the others. The
            // previous primary is otherwise untouched, so the choice is fully reversible.
            state.stackMembers[stackId]?.forEach { row ->
                val member = state.assets[row.assetId] ?: return@forEach
                val membership = member.stack ?: return@forEach
                val isPrimary = row.assetId == primaryAssetId
                state.put(
                    member.copy(
                        stack =
                            membership.copy(
                                role = roleFor(isPrimary),
                                isSuppressed = !isPrimary,
                            ),
                    ),
                )
            }
        }
    }

    override suspend fun setStackHidden(
        assetId: AssetId,
        hidden: Boolean,
    ) {
        backend.gate(MockOperation.StackWrite)
        val asset = backend.requireAsset(assetId)
        val membership = asset.stack ?: throw LocalError.NotFound("stack membership for ${assetId.value}")
        // Distinct from the asset's own hidden flag on purpose: un-stacking must never
        // un-hide something the user deliberately hid.
        backend.mutate { it.put(asset.copy(stack = membership.copy(isSuppressed = hidden))) }
    }

    override suspend fun setCollapsed(
        stackId: StackId,
        collapsed: Boolean,
    ) {
        backend.gate(MockOperation.StackWrite)
        val stack = requireStack(stackId)
        backend.mutate { it.stacks[stackId] = stack.copy(isCollapsed = collapsed) }
    }

    override fun groupCullState(stackId: StackId): Flow<GroupCullState> =
        backend.observe { state, _ ->
            val members =
                state.stackMembers[stackId]
                    .orEmpty()
                    .mapNotNull { state.assets[it.assetId] }
                    .map(Asset::cull)
            deriveGroupCullState(members)
        }

    /** The collapsed-view role a member takes, given whether it is the primary. */
    private fun roleFor(isPrimary: Boolean): Wire<StackRole> =
        when (isPrimary) {
            // A pointer, not a promotion: the collapsed stack shows exactly one member and
            // every other member is suppressed rather than changed.
            true -> StackRole.Primary.asWire()
            false -> StackRole.Member.asWire()
        }

    private fun requireStack(id: StackId): Stack =
        backend.read { it.stacks[id] }
            ?: throw LocalError.NotFound("stack ${id.value}")

    private fun memberRow(
        stackId: StackId,
        assetId: AssetId,
        order: Int,
        role: StackMemberRole,
        at: java.time.Instant,
    ): StackMember =
        StackMember(
            id = StackMemberId(DeterministicIds.uuidV7(at.toEpochMilli(), prng)),
            stackId = stackId,
            assetId = assetId,
            sequenceOrder = order,
            memberRole = role.asWire(),
            createdAt = at,
        )
}
