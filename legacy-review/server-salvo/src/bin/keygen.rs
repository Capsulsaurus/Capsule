//! `capsule-keygen` — mint the secrets a Capsule server needs to boot (slice `S-P7`).
//!
//! `JWT_ED25519_DER` is the only hard-required secret with no default: it signs every access
//! and refresh token, and `SYNC_CURSOR_MAC_KEY` plus `ATTESTATION_KEY_SEED` are HKDF-derived
//! from it when they are not set explicitly. Before this binary the documented way to produce
//! one was an `openssl genpkey` incantation, which put a from-clean-checkout bring-up behind
//! a tool that is not in the repo's pinned toolchain.
//!
//! The key comes from [`environment::generate_signing_key_der`], the same module
//! that parses it at boot, so a key this prints is a key the server accepts.
//!
//! ```text
//! cargo run -p capsule-api --bin keygen           # .env lines, ready to paste
//! cargo run -p capsule-api --bin keygen --raw     # just the base64, for scripts
//! ```

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as BASE64;
use clap::Parser;
use eyre::Result;

#[derive(Parser, Debug)]
#[command(
    name = "keygen",
    about = "Mint a JWT_ED25519_DER signing key for a Capsule server"
)]
struct Args {
    /// Print only the base64 key, with no `KEY=` prefix or commentary — for `$(...)` capture.
    #[arg(long)]
    raw: bool,
}

fn main() -> Result<()> {
    color_eyre::install()?;
    let args = Args::parse();

    let der = environment::generate_signing_key_der()
        .map_err(|_| eyre::eyre!("system RNG unavailable; cannot mint a signing key"))?;
    let encoded = BASE64.encode(&der);

    if args.raw {
        println!("{encoded}");
        return Ok(());
    }

    println!("# Generated by `cargo run -p capsule-api --bin keygen`.");
    println!("# Treat this as a production secret: it signs every access and refresh token,");
    println!("# and SYNC_CURSOR_MAC_KEY + ATTESTATION_KEY_SEED are derived from it by default.");
    println!("# Rotating it invalidates every outstanding session.");
    println!("JWT_ED25519_DER={encoded}");

    Ok(())
}
