/// The typed REST client generated by `spargen` from the server's committed OpenAPI **3.1**
/// schema (`openapi.json`), emitted into `OUT_DIR` by `build.rs` and included verbatim here
/// (slice `S-D8`). One `async` method per operation, typed models, typed errors, and an
/// embedded freestanding `reqwest` runtime — `spargen` never enters the runtime dependency
/// tree. Do not edit: regenerate the schema with `mise run openapi`; the client re-generates
/// on every build. The ergonomic, session-composed entry point is
/// [`client::AuthenticatedClient`]; reach for [`rest::Client`] directly only for
/// unauthenticated calls.
pub mod rest {
    #![allow(
        clippy::all,
        clippy::pedantic,
        clippy::nursery,
        missing_docs,
        unreachable_pub,
        dead_code
    )]
    include!(concat!(env!("OUT_DIR"), "/rest_client.rs"));
}

