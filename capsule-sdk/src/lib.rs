//! Capsule client SDK: the sanctioned network path for every Capsule client
//! (upload protocol, sync/download, auth flows).
//!
//! # REST client generation (spargen; slice `S-D8` in the repo-root `SLICES.md`)
//!
//! The typed REST client ([`rest`]) is generated from the server's **OpenAPI 3.1** schema by
//! `spargen`, our in-house generator, at build time (see `build.rs`). The previous progenitor
//! pipeline is gone deliberately: progenitor consumes OpenAPI 3.0 only, which forced a lossy
//! 3.1→3.0 schema down-conversion — a standing source of drift and failures. We do not
//! downgrade schemas. [`client::AuthenticatedClient`] wraps the generated `Client`, composing
//! it with [`auth`]'s session/token store so callers issue typed calls and never juggle raw
//! tokens. The hand-written upload/sync surfaces ([`upload`], [`sync`]) stay hand-written —
//! their protocols are too stateful for request/response codegen; the generated client covers
//! the plain request/response surfaces (auth, quota, storage-verify, receipts, devices, …).

