//! The committed surface digest of the `capsule-wasm` browser module.
//!
//! `wasm-bindgen` writes `capsule_wasm.d.ts` into the gitignored `capsule-web/src/generated/wasm/`
//! tree, so the bun-only documentation build cannot read it (`design/developer-docs.md`:
//! artifacts cross the boundary, not toolchains). This task copies the declaration file's
//! **public** half into the committed `capsule-wasm/wasm-surface.d.ts`, and with `--check` fails
//! when the committed copy no longer matches what the current build emits.
//!
//! "Public half" is a fixed cut, not a parse. `wasm-bindgen` emits the declarations a caller
//! imports first, then the loader's own `InitInput` / `InitOutput` types, whose `InitOutput`
//! lists every raw `__wbg_*` export with positional `number` arguments. Those are the module's
//! ABI, not its surface, and they churn on every internal signature change, so the digest stops
//! at `export type InitInput`. The two lint-suppression banners at the top are dropped for the
//! same reason. Everything in between is kept verbatim, doc comments included: it is TypeScript
//! wasm-bindgen produced, and re-serializing it would be a second, hand-written description of a
//! format this repository does not own.
//!
//! The check runs in the web gate, not the Rust one: producing the declaration file needs
//! `wasm-bindgen-cli`, which only the `web` CI job installs.

use std::fs;
use std::path::Path;

use eyre::{Context, Result, bail};
use tracing::{debug, info};

/// Repo-relative path of the declaration file `mise run build-wasm` emits.
pub(crate) const SOURCE: &str = "capsule-web/src/generated/wasm/capsule_wasm.d.ts";

/// Repo-relative path of the committed digest.
pub(crate) const DIGEST: &str = "capsule-wasm/wasm-surface.d.ts";

/// The first line of the loader's own declarations — where the public surface ends.
const LOADER_BOUNDARY: &str = "export type InitInput";

/// The banner the digest opens with. Line comments, so a reader that splits the file on
/// `/** … */` blocks never mistakes it for a declaration's documentation.
const BANNER: &str = concat!(
    "// The public surface of the capsule-wasm browser module: the part of the capsule_wasm.d.ts\n",
    "// wasm-bindgen emits that a caller imports. Generated by `mise run wasm-surface`;\n",
    "// `mise run wasm-surface-check` fails the web gate when it drifts. Do not edit.\n",
);

/// Write the digest, or in `check` mode verify the committed one is current.
pub(crate) fn run(root: &Path, check: bool) -> Result<()> {
    let source_path = root.join(SOURCE);
    let declarations = fs::read_to_string(&source_path).with_context(|| {
        format!(
            "reading {SOURCE}; run `mise run build-wasm` first, which emits it with wasm-bindgen"
        )
    })?;
    let rendered = digest(&declarations)?;
    debug!(
        bytes = rendered.len(),
        source = SOURCE,
        "digested the wasm declaration file"
    );

    let digest_path = root.join(DIGEST);
    if check {
        let committed = fs::read_to_string(&digest_path)
            .with_context(|| format!("reading the committed digest {DIGEST}"))?;
        if committed != rendered {
            bail!(
                "{DIGEST} is out of sync with the capsule-wasm surface; run `mise run \
                 wasm-surface` and commit the result"
            );
        }
        info!(digest = DIGEST, "wasm surface digest is up to date");
    } else {
        fs::write(&digest_path, &rendered)
            .with_context(|| format!("writing {}", digest_path.display()))?;
        info!(digest = DIGEST, "wrote the wasm surface digest");
    }
    Ok(())
}

/// The digest of a `wasm-bindgen` declaration file: [`BANNER`], then every line between the
/// lint-suppression banners and the loader's declarations, with one trailing newline.
///
/// Fails rather than degrading when the file is not shaped the way this cut assumes: a missing
/// loader boundary means `wasm-bindgen` changed its layout, and a surface with no `export`
/// means the build exported nothing. Either would otherwise commit a digest that documents a
/// confidently wrong surface.
pub(crate) fn digest(declarations: &str) -> Result<String> {
    let Some(end) = declarations
        .lines()
        .position(|line| line.starts_with(LOADER_BOUNDARY))
    else {
        bail!(
            "the declaration file has no `{LOADER_BOUNDARY}` line; wasm-bindgen's layout changed, \
             so update xtask/src/wasm_surface.rs rather than committing a digest of the loader"
        );
    };
    let lines: Vec<&str> = declarations
        .lines()
        .take(end)
        .skip_while(|line| is_lint_banner(line))
        .collect();
    let body = lines.join("\n");
    let body = body.trim_end();
    if !body.lines().any(|line| line.starts_with("export ")) {
        bail!("the declaration file exports nothing before `{LOADER_BOUNDARY}`");
    }
    Ok(format!("{BANNER}\n{body}\n"))
}

/// A `/* tslint:disable */`-style single-line suppression comment at the top of the file.
fn is_lint_banner(line: &str) -> bool {
    let line = line.trim();
    line.starts_with("/* ") && line.ends_with(" */") && line.contains("disable")
}

